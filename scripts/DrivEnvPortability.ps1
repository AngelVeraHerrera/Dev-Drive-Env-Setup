function Get-DrivEnvBuildtreeEntryKind
{
    # @brief What one folder under the buildtrees root is: 'port' (carries a <triplet>.vcpkg_abi_info.txt stamp),
    # 'user' (named after a declared triplet: DEVSYSTEM_BUILDTREES), 'internal' (detect_compiler) or 'unknown'.
    param ([string]$Name, [string[]]$FileNames = @(), [string[]]$Triplets = @())

    if (@($FileNames | Where-Object { $_ -like '*.vcpkg_abi_info.txt' }).Count -gt 0) { return 'port' }
    if (@($Triplets | Where-Object { $_ -and ($_ -ieq $Name) }).Count -gt 0) { return 'user' }
    if ($Name -ieq 'detect_compiler') { return 'internal' }
    return 'unknown'
}

function Get-DrivEnvPortabilityCategories
{
    # @brief The cleanup categories of a drive, with their class and the paths they cover:
    #   safe      regenerated by vcpkg without loss (staging, logs of good builds, scratch, temp)
    #   optional  regenerable at a cost (re-download, rebuild) or the user's own data
    #   keep      reported, never removed (the environment, the sources, the records)
    # @param Drive        Drive root, e.g. "D:\".
    # @param BuildtreesWin The buildtrees root (Resolve-DrivEnvBuildtreesRoot).
    # @param BinaryCache  The vcpkg binary cache folder.
    # @return [pscustomobject]@{ Key; Class; Paths; Description; Effect } in display order.
    param ([string]$Drive, [string]$BuildtreesWin, [string]$BinaryCache)

    $d = $Drive.TrimEnd('\') + '\'
    $vcpkg = $d + 'vcpkg'
    return @(
        [pscustomobject]@{ Key = 'vcpkg_packages';  Class = 'safe';     Paths = @("$vcpkg\packages");  Description = 'vcpkg staging (packages\<port>_<triplet>)'; Effect = 'none: recreated when a port is built' }
        [pscustomobject]@{ Key = 'buildtree_ports'; Class = 'safe';     Paths = @($BuildtreesWin);      Description = 'vcpkg port folders in the build trees (logs, leftovers)'; Effect = 'build logs of finished ports are lost' }
        [pscustomobject]@{ Key = 'buildtree_internal'; Class = 'safe';  Paths = @("$BuildtreesWin\detect_compiler"); Description = "vcpkg's compiler detection scratch"; Effect = 'none' }
        [pscustomobject]@{ Key = 'temp';            Class = 'safe';     Paths = @($d + 'tmp');          Description = 'drive temporary folder'; Effect = 'none when nothing is running' }
        [pscustomobject]@{ Key = 'downloads';       Class = 'optional'; Paths = @("$vcpkg\downloads"); Description = 'vcpkg downloads (source archives, tools)'; Effect = 'rebuilding a port downloads again (needs network)' }
        [pscustomobject]@{ Key = 'user_builds';     Class = 'optional'; Paths = @($BuildtreesWin);      Description = 'your build trees (DEVSYSTEM_BUILDTREES, bt\<triplet>\...)'; Effect = 'projects must be rebuilt' }
        [pscustomobject]@{ Key = 'failure_logs';    Class = 'optional'; Paths = @($d + 'logs\vcpkg');   Description = 'logs of failed port attempts'; Effect = 'history of failures is lost' }
        [pscustomobject]@{ Key = 'binary_cache';    Class = 'optional'; Paths = @($BinaryCache);        Description = 'vcpkg binary cache'; Effect = 'reinstalling means building again; the Rebuild mode needs it' }
        [pscustomobject]@{ Key = 'environment';     Class = 'keep';     Paths = @(($d + 'msys64'), "$vcpkg\installed", ($d + 'env')); Description = 'MSYS2, installed ports, env files'; Effect = 'removing it breaks the environment' }
        [pscustomobject]@{ Key = 'records';         Class = 'keep';     Paths = @(($d + 'logs\setup'), ($d + 'installation')); Description = 'setup logs and records'; Effect = 'traceability' }
    )
}

function Get-DrivEnvExportExclusions
{
    # @brief The category keys an export leaves out of the copy: every 'safe' one always (vcpkg_packages above all:
    # its files are hardlinked into installed, and a file copy would duplicate them), plus the optional ones chosen.
    # @param Full    Leave out every optional category too.
    # @param Exclude Optional category keys to leave out.
    # @return The keys, in category order. Throws on a key that is not an optional category.
    param ($Categories, [switch]$Full, [string[]]$Exclude = @())

    $optional = @($Categories | Where-Object Class -eq 'optional' | ForEach-Object Key)
    foreach ($k in $Exclude) { if ($k -and ($optional -notcontains $k)) { throw "Not an optional category: '$k'. Optional: $($optional -join ', ')." } }
    return @($Categories | Where-Object { ($_.Class -eq 'safe') -or (($_.Class -eq 'optional') -and ($Full -or ($Exclude -contains $_.Key))) } | ForEach-Object Key)
}
